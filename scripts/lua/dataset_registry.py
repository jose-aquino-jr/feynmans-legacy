"""Authoritative registry of every lunar dataset considered by the pipeline.

Each entry documents provenance (mission, instrument, product, version, identifier,
URL, documentation, institution), its physical meaning (variables, units), its
spatial/temporal properties, its acquisition mode and WHAT IT ADDS (anti-redundancy
rule).  `acquisition`:
  full          - whole file downloaded to data/raw (kept unaltered)
  stream        - whole file downloaded, reduced to a processed product, then the raw
                  copy is deleted (disk limit ~5 GB); SHA-256 kept in manifest
  remote_rows   - systematic subset of image lines read from the archive with HTTP
                  Range requests (native values); stride recorded
  catalog_only  - catalogued, not acquired (reason given)
  rejected      - examined and rejected (reason given)
"""

